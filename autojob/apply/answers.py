"""Builds the answer set a handler fills a form from: profile facts, the
reusable answer bank for recurring questions, and a per-job cover letter
plus screening-question answers generated by the local claude CLI.

Every prompt sent to the model carries Sean's honest profile and an
explicit instruction not to fabricate anything. Sean is a JUNIOR
penetration tester: HTB CPTS, TCM PNPT and eJPT certified, 100+
HackTheBox/TryHackMe machines completed, a home Active Directory lab he
built and maintains, and close to no professional, paid pentest experience.
Any "years of experience" style answer must say 0 to 1 years and lean on
the certifications and labs, never the inflated claims his CV's prose
makes. This file, not the CV text, is the source of truth for what gets
typed into a form.
"""

from __future__ import annotations

from pathlib import Path

from autojob.llm.cli import ClaudeCliError, extract_json, run_claude

ANSWERS_MODEL = "sonnet"
ANSWERS_TIMEOUT = 180

HONESTY_INSTRUCTIONS = (
    "Sean is a JUNIOR penetration tester. He holds HTB CPTS, TCM PNPT and eJPT, "
    "has completed 100+ HackTheBox/TryHackMe machines, and has built and maintains a "
    "home Active Directory lab. He has close to no professional, paid penetration "
    "testing experience: treat his years of professional experience as 0 to 1, never "
    "more. Do not fabricate experience, employers, achievements, or credentials. Never "
    "claim years of professional experience he does not have. If something isn't "
    "covered by the facts given, answer honestly and briefly rather than inventing a "
    "number or a claim."
)

# Recurring questions almost every application asks. Seeded from the
# profile where it has a real answer, otherwise a conservative, honest
# default, so the same question gets the same answer everywhere.
DEFAULT_ANSWER_BANK = {
    "years_experience": (
        "0 to 1 years of paid, professional penetration testing experience. "
        "Certified via HTB CPTS, TCM PNPT and eJPT, with 100+ HackTheBox/TryHackMe "
        "machines completed and a self-built home Active Directory lab."
    ),
    "visa_sponsorship": "No visa sponsorship needed.",
    "relocation": "Open to discussing relocation for the right role.",
    "salary_expectation": "Open to discussing, based on the role.",
}


def seed_answer_bank(profile_answers: dict) -> dict:
    bank = dict(DEFAULT_ANSWER_BANK)
    if profile_answers.get("willing_to_relocate"):
        bank["relocation"] = profile_answers["willing_to_relocate"]
    if profile_answers.get("salary_expectation"):
        bank["salary_expectation"] = profile_answers["salary_expectation"]
    return bank


def build_answer_set(profile_answers: dict, answer_bank: dict) -> dict:
    """Flatten the profile facts and the answer bank into one dict a
    handler can pull field values from directly."""
    answers = dict(profile_answers)
    answers.update(answer_bank)
    return answers


def _fallback_cover_letter(profile_answers: dict, job: dict) -> str:
    name = profile_answers.get("full_name") or "Sean"
    title = job.get("title") or "this role"
    company = job.get("company") or "your team"
    return (
        f"Dear {company} hiring team,\n\n"
        f"I would like to apply for the {title} role. I am an early-career penetration "
        "tester: certified through HTB CPTS, TCM PNPT and eJPT, with 100+ HackTheBox and "
        "TryHackMe machines completed and a home Active Directory lab I built and "
        "maintain. I do not have professional pentest experience yet, and I am looking "
        "for a role where I can build it.\n\n"
        f"Thank you for your consideration.\n\n{name}"
    )


def _build_prompt(profile_answers: dict, answer_bank: dict, job: dict, company_tldr: str) -> str:
    profile_lines = "\n".join(f"- {k}: {v}" for k, v in profile_answers.items() if v)
    bank_lines = "\n".join(f"- {k}: {v}" for k, v in answer_bank.items())
    description = (job.get("description") or "").strip()[:3000]
    return (
        "Write an honest job application cover letter and screening-question answers "
        "for Sean, a penetration tester.\n\n"
        f"{HONESTY_INSTRUCTIONS}\n\n"
        f"Sean's profile:\n{profile_lines or '(none on file)'}\n\n"
        f"Standard answers to recurring questions:\n{bank_lines}\n\n"
        f"Job title: {job.get('title', '')}\n"
        f"Company: {job.get('company', '')}\n"
        f"Company summary: {company_tldr or 'unknown'}\n"
        f"Job description:\n{description or '(no description available)'}\n\n"
        "Respond with ONLY a JSON object: "
        '{"cover_letter": "3 to 5 short paragraphs, plain text, no markdown, honest and '
        'specific to this company and role, mentions the certifications and hands-on labs, '
        'never claims years of professional experience he does not have", '
        '"screening_answers": {"<short question or field name>": "<honest short answer>"}}. '
        "Only include screening_answers you can answer honestly from the facts given, and "
        "leave the object empty if none apply. No prose, no markdown fences, just the JSON "
        "object."
    )


def generate_application_content(
    profile_answers: dict,
    answer_bank: dict,
    job: dict,
    company_tldr: str,
    *,
    work_dir: Path,
) -> dict:
    """Generate {"cover_letter": str, "screening_answers": dict} for one job.

    On any claude CLI failure this returns a safe, honest fallback cover
    letter built straight from the profile (no LLM involved) and no
    screening answers, rather than raising past the apply flow.
    """
    try:
        prompt = _build_prompt(profile_answers, answer_bank, job, company_tldr)
        raw = run_claude(prompt, model=ANSWERS_MODEL, cwd=work_dir, timeout=ANSWERS_TIMEOUT)
        parsed = extract_json(raw)
        if not isinstance(parsed, dict):
            raise ClaudeCliError("answer generation response was not a JSON object")
        cover_letter = str(parsed.get("cover_letter") or "").strip()
        screening_answers = parsed.get("screening_answers")
        return {
            "cover_letter": cover_letter or _fallback_cover_letter(profile_answers, job),
            "screening_answers": screening_answers if isinstance(screening_answers, dict) else {},
        }
    except ClaudeCliError:
        return {
            "cover_letter": _fallback_cover_letter(profile_answers, job),
            "screening_answers": {},
        }
